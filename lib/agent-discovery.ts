const MARKDOWN_TYPE = "text/markdown";

export function acceptsMarkdown(acceptHeader: string | null) {
  return (acceptHeader || "")
    .split(",")
    .map((value) => value.split(";", 1)[0].trim().toLowerCase())
    .includes(MARKDOWN_TYPE);
}

